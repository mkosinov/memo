# scripts/lib/test-lock.sh — замок тяжёлых прогонов контейнера (GH #472).
#
# Спека: docs/specs/2026-10-22-test-concurrency-lock-472-design.md, секция
# «Механизм замка» + «Точки входа под замком». Это БИБЛИОТЕКА (сурсится,
# не исполняется); потребители:
#   - scripts/with-test-lock.sh — обёртка одиночных тяжёлых наборов
#     (полный pytest бэкенда, полные vitest-наборы);
#   - scripts/test-all.sh — встроенный самозахват полного прогона.
#
# Env-швы (идиома «${VAR:-default}», как SHARD_RUNS_DIR):
#   MEMO_TEST_LOCK_PATH  — путь файла замка (дефолт
#                          /root/workspace/.memo-heavy-tests.lock — фикси-
#                          рованный абсолютный путь НА томе контейнера,
#                          вне git-копий и ворктри, общий для всех сессий);
#   MEMO_LOCK_POLL_S     — интервал повторных попыток (дефолт 300 с);
#   MEMO_LOCK_WAIT_S     — потолок ожидания по ФАКТИЧЕСКОМУ времени
#                          (дефолт 3600 с);
#   MEMO_TEST_LOCK_DISABLE=1 — обход без замка (однострочное уведомление);
#   MEMO_TEST_LOCK_HELD=1    — предохранитель реентерабельности: сессия
#                          УЖЕ держит замок — захват не выполняется.
#
# Контракт дескриптора: замок живёт на fd 9 ПРОЦЕССА-ВЛАДЕЛЬЦА. Ядро
# закрывает дескриптор при любой смерти процесса (включая kill -9) —
# освобождение мгновенное. НО порождаемые процессы, унаследовавшие fd 9,
# продолжают держать замок и после смерти владельца: каждый порождаемый
# процесс (фоновые стадии test-all, команда обёртки) обязан запускаться
# с закрытым дескриптором — `9>&-` в редиректах команды. Закрытие
# неоткрытого fd безвредно, поэтому `9>&-` пишется всегда, независимо от
# того, был ли захвачен замок.
#
# Очередь (решение пользователя, Gate A): первая попытка немедленно
# (flock -n); занят → статус-строка и повтор каждые MEMO_LOCK_POLL_S;
# потолок MEMO_LOCK_WAIT_S — по фактическому времени ожидания (сон усечён
# до остатка). Выбор опроса вместо блокирующего flock -w осознан:
# статус-строки для человека/агента ценнее мгновенной передачи; порядок
# очереди не гарантирован (flock не FIFO) — при imac=2 допустимо.
#
# Обход (прогон без замка, однострочное уведомление; подавляется при
# CI=true): каталог замка отсутствует или недоступен для записи, ИЛИ нет
# бинарника flock, ИЛИ MEMO_TEST_LOCK_DISABLE=1. Каталог замка НИКОГДА не
# создаётся. Файл замка создаётся пустым при первом захвате, но никогда
# не удаляется и не пересоздаётся (unlink молча ломает взаимное
# исключение — два владельца на двух inode).
#
# Соотношение с seed-замком test-all.sh (mkdir вокруг сидирования) —
# сознательно разные идиомы: seed-замок короткий и мягкий, тяжёлый замок
# строгий на всё время прогона. Не «унифицировать» (спека).

# Дескриптор замка — фиксированный fd 9 (см. контракт выше).
HEAVY_TEST_LOCK_FD=9

# _memo_lock_num VALUE DEFAULT MIN → stdout: нормализованное целое ≥ MIN.
# Идиома _watch_interval_s (shard-helpers.sh): не-число/пусто/меньше
# минимума → дефолт; 10# — ведущие нули не восьмеричные; ERE через
# переменную (портабельная форма =~).
_memo_lock_num() {
  local v="${1:-}" d="$2" min="$3" n
  local num_re='^[0-9]+$'
  if [[ "$v" =~ $num_re ]]; then
    n=$((10#$v))
    if [ "$n" -ge "$min" ]; then
      printf '%s\n' "$n"
      return 0
    fi
  fi
  printf '%s\n' "$d"
}

# heavy_test_lock_notice ПРИЧИНА — однострочное уведомление об обходе.
# Подавляется при CI=true (CI-раннер и так сериализован, шум не нужен).
heavy_test_lock_notice() {
  [ "${CI:-}" = "true" ] && return 0
  echo "[lock] обход без замка: $1 — прогон НЕ сериализован"
  return 0
}

# heavy_test_lock_acquire — захват замка на fd 9 ВЫЗЫВАЮЩЕЙ оболочки.
#
# Результаты:
#   rc 0  — замок захвачен (экспортирован MEMO_TEST_LOCK_HELD=1) ИЛИ
#           сквозной запуск (HELD=1 уже стоит) ИЛИ обход (замок недоступен;
#           прогон идёт без замка, уведомление однострочное);
#   rc 75 — потолок MEMO_LOCK_WAIT_S исчерпан: машина занята чужим тяжёлым
#           прогоном. Вызывающий под set -e завершится кодом 75 (отличим
#           от падения тестов для автоматизации).
heavy_test_lock_acquire() {
  # Реентерабельность (US-1): сессия уже держит замок — захват не
  # выполняем, сквозной запуск. Предохранитель от самозахвата: вложенный
  # test-all/обёртка не встаёт в очередь за самим собой.
  if [ "${MEMO_TEST_LOCK_HELD:-}" = "1" ]; then
    echo "[lock] MEMO_TEST_LOCK_HELD=1 — замок уже удерживается этой сессией, захват пропущен"
    return 0
  fi
  # Обход: явное отключение.
  if [ "${MEMO_TEST_LOCK_DISABLE:-}" = "1" ]; then
    heavy_test_lock_notice "MEMO_TEST_LOCK_DISABLE=1"
    return 0
  fi
  # Обход: нет бинарника flock (не-Linux/урезанный PATH хоста).
  if ! command -v flock >/dev/null 2>&1; then
    heavy_test_lock_notice "нет бинарника flock"
    return 0
  fi
  local _path="${MEMO_TEST_LOCK_PATH:-/root/workspace/.memo-heavy-tests.lock}"
  # dirname без внешнего бинарника (чистый bash): сам код ОБХОДА не должен
  # зависеть от coreutils — деградированный PATH это его рабочий случай.
  local _dir
  case "$_path" in
    */*) _dir="${_path%/*}" ;;
    *)   _dir="." ;;
  esac
  # Обход: каталог замка отсутствует или недоступен для записи. Дискри-
  # минатор — доступность пути и инструмента, не «контейнерность»:
  # Linux-хост с записуемым /root/workspace начнёт сериализовать свои
  # прогоны (осознанное следствие, отключается MEMO_TEST_LOCK_DISABLE=1).
  # Каталог никогда не создаём.
  if [ ! -d "$_dir" ] || [ ! -w "$_dir" ]; then
    heavy_test_lock_notice "каталог замка недоступен для записи: $_dir"
    return 0
  fi
  # Файл замка: открыть на дозапись (без усечения), создать пустым при
  # первом захвате. Проба перед exec: отказ открытия на exec-редиректе
  # роняет неинтерактивную оболочку — переживать это незачем.
  if ! : >> "$_path" 2>/dev/null; then
    heavy_test_lock_notice "файл замка недоступен для записи: $_path"
    return 0
  fi
  local _poll _wait
  _poll="$(_memo_lock_num "${MEMO_LOCK_POLL_S:-}" 300 1)"
  _wait="$(_memo_lock_num "${MEMO_LOCK_WAIT_S:-}" 3600 0)"

  # fd 9 открывается в вызывающей оболочке и живёт до её завершения
  # (нормальный выход ИЛИ любой сигнал — EXIT-трап потребителя не
  # трогаем, дескриптор закрывает само ядро).
  exec 9>>"$_path"

  local _t0=$SECONDS _elapsed _remaining
  while :; do
    if flock -n "$HEAVY_TEST_LOCK_FD"; then
      _elapsed=$(( SECONDS - _t0 ))
      if [ "$_elapsed" -gt 0 ]; then
        echo "[lock] замок захвачен после ${_elapsed} с ожидания ($_path)"
      else
        echo "[lock] замок захвачен ($_path)"
      fi
      export MEMO_TEST_LOCK_HELD=1
      return 0
    fi
    _elapsed=$(( SECONDS - _t0 ))
    _remaining=$(( _wait - _elapsed ))
    if [ "$_remaining" -le 0 ]; then
      echo "❌ [lock] машина занята чужим тяжёлым прогоном дольше 60 мин; перезапусти прогон позже" >&2
      echo "   потолок ожидания ${_wait} с исчерпан (ждали ${_elapsed} с, файл $_path)" >&2
      return 75
    fi
    echo "[lock] занят, ожидание $(( _elapsed / 60 ))/$(( _wait / 60 )) мин (прошло ${_elapsed} с)"
    # Сон усечён до остатка потолка — провал строго по фактическому
    # времени, не по счётчику итераций; после усечённого сна делается
    # ещё одна попытка (допуск — один интервал опроса).
    if [ "$_remaining" -lt "$_poll" ]; then
      sleep "$_remaining"
    else
      sleep "$_poll"
    fi
  done
}
