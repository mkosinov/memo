#!/usr/bin/env bash
# with-test-lock.sh — обёртка тяжёлых прогонов под замком контейнера
# (GH #472, точка входа 2/3 спеки: полный pytest бэкенда, полные наборы
# vitest). Канон запуска — docs/tests_workflow.md; test-all.sh этой
# обёрткой НЕ оборачивается (у него встроенный самозахват).
#
# Usage: scripts/with-test-lock.sh <команда...>
#
# Захватывает flock на ${MEMO_TEST_LOCK_PATH:-/root/workspace/.memo-heavy-
# tests.lock} (немедленная попытка → статус-строка и повторы каждые
# MEMO_LOCK_POLL_S, потолок MEMO_LOCK_WAIT_S по фактическому времени),
# затем запускает команду и ждёт её завершения; код выхода обёртки — код
# команды. Машина занята дольше потолка → код 75.
#
# Замок удерживает сам процесс обёртки: kill -9 обёртки освобождает замок
# мгновенно (ядро закрывает fd), выжившие сироты команды замок НЕ держат
# (команда стартует с закрытым дескриптором 9>&-).
#
# Обход без замка (однострочное уведомление, подавляется при CI=true):
# каталог замка отсутствует/недоступен для записи, нет flock,
# MEMO_TEST_LOCK_DISABLE=1. Каталог замка никогда не создаётся.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
# shellcheck disable=SC1091
source "$SCRIPT_DIR/lib/test-lock.sh"

if [ "$#" -eq 0 ]; then
  echo "usage: $0 <команда...>" >&2
  exit 64
fi

heavy_test_lock_acquire

# Команда — БЕЗ дескриптора замка (9>&-): замок держит только процесс
# обёртки. MEMO_TEST_LOCK_HELD=1 уже экспортирован захватом — вложенные
# тяжёлые вызовы идут сквозным запуском, не встают в очередь за родителем.
"$@" 9>&-
